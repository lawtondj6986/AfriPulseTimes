// AfriPulse Times — generate public/supabase-config.js from VITE_ env vars.
//
// The SPA (public/afripulse-preview.html) is a static file Vite doesn't process,
// so it can't read import.meta.env directly. This script bakes the PUBLIC
// Supabase values (URL + anon key — safe to ship, guarded by RLS) into the
// browser client at predev/prebuild time, so VITE_SUPABASE_URL /
// VITE_SUPABASE_ANON_KEY are the single source of truth (.env.local locally,
// Vercel project env in CI). Never reference the service_role key here.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { loadEnv } from 'vite';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const mode = process.env.NODE_ENV === 'production' ? 'production' : 'development';

// loadEnv merges .env* files AND prefixed process.env vars (so Vercel's build
// environment overrides the local files).
const env = loadEnv(mode, root, 'VITE_');
const url = env.VITE_SUPABASE_URL || 'https://YOUR_PROJECT_REF.supabase.co';
const key = env.VITE_SUPABASE_ANON_KEY || 'YOUR_SUPABASE_ANON_KEY';

const out = `// AfriPulse Times — browser Supabase client.
// GENERATED by scripts/gen-supabase-config.mjs — do not edit by hand.
// Values come from VITE_SUPABASE_URL / VITE_SUPABASE_ANON_KEY (run \`npm run gen:config\`).
// The anon key is PUBLIC and safe to ship — Row Level Security guards the data.
// Never put the service_role key here; server code uses it via /api routes.
import { createClient } from 'https://esm.sh/@supabase/supabase-js@2';

const SUPABASE_URL = ${JSON.stringify(url)};
const SUPABASE_ANON_KEY = ${JSON.stringify(key)};

export const supabase = createClient(SUPABASE_URL, SUPABASE_ANON_KEY, {
  auth: { persistSession: true, autoRefreshToken: true, detectSessionInUrl: true }
});

// Hand the client to afripulse-preview.html's store (see window.__supabaseReady).
window.__supabase = supabase;
if (typeof window.__supabaseResolve === 'function') window.__supabaseResolve(supabase);
`;

writeFileSync(resolve(root, 'public/supabase-config.js'), out);
const tag = (v) => (v.includes('YOUR_') ? 'placeholder' : 'set');
console.log(`[gen:config] wrote public/supabase-config.js (url=${tag(url)}, anon_key=${tag(key)})`);
